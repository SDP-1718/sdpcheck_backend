CREATE TABLE push_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type VARCHAR(30) NOT NULL CHECK (event_type IN ('NEW_NOTICE', 'SESSION_STARTED')),
    resource_id UUID NOT NULL,
    token_id BIGINT NOT NULL REFERENCES push_tokens(id) ON DELETE CASCADE,
    member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    title VARCHAR(100) NOT NULL,
    body VARCHAR(200) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'SENT', 'FAILED', 'SKIPPED')),
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (event_type, resource_id, token_id)
);

CREATE INDEX idx_push_outbox_pending ON push_outbox (next_attempt_at, id) WHERE status = 'PENDING';
